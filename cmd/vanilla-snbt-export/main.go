// Command vanilla-snbt-export exports the pinned JDK's SNBT character-name database.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	output := flag.String("output", "server/internal/javanbt/unicode_names_generated.go", "generated Go output")
	flag.Parse()
	if err := export(*output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func export(output string) error {
	java := os.Getenv("JAVA")
	if java == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return err
		}
		java = filepath.Join(home, ".cache/adamant-vanilla/jdk-25.0.4.1/bin/java")
	}
	dir, err := os.MkdirTemp("", "adamant-unicode-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "UnicodeNames.java")
	const source = `public class UnicodeNames {
    public static void main(String[] args) {
        if (Runtime.version().feature() != 25) throw new IllegalStateException("expected JDK 25");
        System.out.println("VERSION\t" + Runtime.version());
        var snbtNames = java.util.regex.Pattern.compile("[-a-zA-Z0-9 ]+").matcher("");
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            String name = Character.getName(cp);
            if (name != null && snbtNames.reset(name).matches()) {
                if (Character.codePointOf(name) != cp) throw new IllegalStateException("non-invertible name: " + name);
                System.out.println(Integer.toHexString(cp) + "\t" + name);
            }
        }
    }
}`
	if err := os.WriteFile(path, []byte(source), 0600); err != nil {
		return err
	}
	command := exec.Command(java, path)
	command.Stderr = os.Stderr
	data, err := command.Output()
	if err != nil {
		return fmt.Errorf("export Java character names: %w", err)
	}
	type named struct {
		name string
		cp   int64
	}
	type interval struct {
		prefix   string
		min, max int64
	}
	var names []named
	var ranges []interval
	var version string
	scanner := bufio.NewScanner(bytes.NewReader(data))
	count := 0
	for scanner.Scan() {
		left, name, ok := strings.Cut(scanner.Text(), "\t")
		if !ok {
			return fmt.Errorf("invalid exporter row %q", scanner.Text())
		}
		if left == "VERSION" {
			version = name
			continue
		}
		cp, err := strconv.ParseInt(left, 16, 32)
		if err != nil {
			return err
		}
		count++
		suffix := " " + strings.ToUpper(left)
		if strings.HasSuffix(name, suffix) {
			prefix := strings.TrimSuffix(name, suffix)
			if n := len(ranges); n > 0 && ranges[n-1].prefix == prefix && ranges[n-1].max+1 == cp {
				ranges[n-1].max = cp
			} else {
				ranges = append(ranges, interval{prefix, cp, cp})
			}
		} else {
			names = append(names, named{name, cp})
		}
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	if version == "" || count == 0 {
		return fmt.Errorf("missing source version or character names")
	}
	sort.Slice(names, func(i, j int) bool { return names[i].name < names[j].name })
	var code bytes.Buffer
	fmt.Fprintf(&code, "// Code generated by cmd/vanilla-snbt-export from JDK %s; DO NOT EDIT.\npackage javanbt\n\n", version)
	fmt.Fprintln(&code, "var javaUnicodeNames = [...]struct { name string; codePoint rune }{")
	for _, row := range names {
		fmt.Fprintf(&code, "{%q, 0x%X},\n", row.name, row.cp)
	}
	fmt.Fprintln(&code, "}\n\nvar javaUnicodeNameRanges = [...]struct { prefix string; min, max rune }{")
	for _, row := range ranges {
		fmt.Fprintf(&code, "{%q, 0x%X, 0x%X},\n", row.prefix, row.min, row.max)
	}
	fmt.Fprintln(&code, "}")
	formatted, err := format.Source(code.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(output, formatted, 0644); err != nil {
		return err
	}
	fmt.Printf("JDK %s: %d names, %d explicit records, %d algorithmic ranges\n", version, count, len(names), len(ranges))
	return nil
}
