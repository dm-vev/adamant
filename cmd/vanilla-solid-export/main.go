// Command vanilla-solid-export converts the Java oracle's TSV report into
// allocation-free Go lookups used by javadata.
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"
)

const reportHeader = "# Java 26.3 BLOCK defaults, solidity and generation faces export; generated by cmd/vanilla-solid-export"
const pinnedBlockCount = 1286

type defaultProperty struct {
	name  string
	kind  string
	value string
}

func main() {
	input := flag.String("input", "", "Java BLOCK defaults and solidity TSV report")
	output := flag.String("output", "", "generated Go solidity source path")
	defaultsOutput := flag.String("defaults-output", "", "generated Go block defaults source path")
	facesOutput := flag.String("faces-output", "", "generated Go generation-face source path")
	flag.Parse()
	if *input == "" || *output == "" || *defaultsOutput == "" || *facesOutput == "" || flag.NArg() != 0 {
		fatal(errors.New("usage: go run ./cmd/vanilla-solid-export -input report.tsv -output solidity.go -defaults-output defaults.go -faces-output faces.go"))
	}
	if err := generate(*input, *output, *defaultsOutput, *facesOutput); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "vanilla-solid-export:", err)
	os.Exit(1)
}

func generate(input, output, defaultsOutput, facesOutput string) error {
	file, err := os.Open(input)
	if err != nil {
		return err
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	scanner.Buffer(make([]byte, 4096), 4<<20)
	if !scanner.Scan() || scanner.Text() != reportHeader {
		return errors.New("input is not a Java 26.3 BLOCK defaults and solidity report")
	}
	var names []string
	var solid []bool
	var defaults [][]defaultProperty
	var faces [][]faceState
	blockIndex := -1
	for scanner.Scan() {
		line := scanner.Text()
		fields := strings.Split(line, "\t")
		switch {
		case len(fields) == 3 && fields[0] == "B":
			if !strings.HasPrefix(fields[1], "minecraft:") || (fields[2] != "0" && fields[2] != "1") {
				return fmt.Errorf("malformed block solidity row %q", line)
			}
			names = append(names, strings.TrimPrefix(fields[1], "minecraft:"))
			solid = append(solid, fields[2] == "1")
			defaults = append(defaults, nil)
			faces = append(faces, nil)
			blockIndex++
		case len(fields) == 3 && fields[0] == "D":
			if blockIndex < 0 || fields[1] != "minecraft:"+names[blockIndex] || defaults[blockIndex] != nil {
				return fmt.Errorf("malformed or misplaced block defaults row %q", line)
			}
			properties, err := parseProperties(fields[2])
			if err != nil {
				return fmt.Errorf("malformed block defaults row %q: %w", line, err)
			}
			defaults[blockIndex] = properties
		case len(fields) == 4 && fields[0] == "F":
			if blockIndex < 0 || fields[1] != "minecraft:"+names[blockIndex] {
				return fmt.Errorf("misplaced generation-face row %q", line)
			}
			properties, err := parseProperties(fields[2])
			if err != nil {
				return err
			}
			mask, err := strconv.ParseUint(fields[3], 10, 21)
			if err != nil {
				return fmt.Errorf("invalid face mask %q: %w", fields[3], err)
			}
			faces[blockIndex] = append(faces[blockIndex], faceState{properties: properties, mask: uint32(mask)})
		default:
			return fmt.Errorf("state-dependent or malformed solidity row %q; regenerate after updating lookup representation", line)
		}
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	if len(names) == 0 {
		return errors.New("Java BLOCK report contains no block rows")
	}
	if len(names) != pinnedBlockCount {
		return fmt.Errorf("Java 26.3 BLOCK report has %d blocks, want %d", len(names), pinnedBlockCount)
	}
	for i := range names {
		if defaults[i] == nil {
			return fmt.Errorf("Java BLOCK report is missing defaults for %q", names[i])
		}
		if i > 0 && names[i-1] >= names[i] {
			return fmt.Errorf("Java BLOCK names are not unique and sorted: %q then %q", names[i-1], names[i])
		}
	}

	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by cmd/vanilla-solid-export from the pinned Java 26.3 BLOCK registry; DO NOT EDIT.")
	fmt.Fprint(&source, "// Source classifier: net.minecraft.world.level.block.state.BlockState.isSolid().\n\npackage javadata\n\n")
	fmt.Fprintln(&source, "var javaSolidBlockNames = [...]string{")
	for _, name := range names {
		fmt.Fprintf(&source, "\t%q,\n", name)
	}
	fmt.Fprintln(&source, "}\n\nvar javaSolidBlockBits = [...]uint64{")
	for base := 0; base < len(solid); base += 64 {
		var word uint64
		for offset := range min(64, len(solid)-base) {
			if solid[base+offset] {
				word |= uint64(1) << offset
			}
		}
		fmt.Fprintf(&source, "\t0x%016x,\n", word)
	}
	fmt.Fprintln(&source, "}")
	if err := os.WriteFile(output, []byte(source.String()), 0o644); err != nil {
		return err
	}

	var defaultsSource strings.Builder
	fmt.Fprintln(&defaultsSource, "// Code generated by cmd/vanilla-solid-export from the pinned Java 26.3 BLOCK registry; DO NOT EDIT.")
	fmt.Fprint(&defaultsSource, "// Source: Block.defaultBlockState() and Property.getName(value).\n\npackage javadata\n\n")
	fmt.Fprintln(&defaultsSource, "var javaBlockDefaultProperties = [...]map[string]any{")
	for _, properties := range defaults {
		fmt.Fprint(&defaultsSource, "\t{")
		for _, property := range properties {
			fmt.Fprintf(&defaultsSource, "%q: %s, ", property.name, goValue(property))
		}
		fmt.Fprintln(&defaultsSource, "},")
	}
	fmt.Fprintln(&defaultsSource, "}")
	if err := os.WriteFile(defaultsOutput, []byte(defaultsSource.String()), 0o644); err != nil {
		return err
	}
	return generateFaces(facesOutput, names, faces)
}

func parseProperties(encoded string) ([]defaultProperty, error) {
	if encoded == "" {
		return []defaultProperty{}, nil
	}
	parts := strings.Split(encoded, ",")
	properties := make([]defaultProperty, 0, len(parts))
	for _, part := range parts {
		name, encodedValue, ok := strings.Cut(part, "=")
		kind, value, hasValue := strings.Cut(encodedValue, ":")
		if !ok || !hasValue || name == "" || value == "" || (kind != "b" && kind != "i" && kind != "s") {
			return nil, fmt.Errorf("invalid property %q", part)
		}
		if len(properties) > 0 && properties[len(properties)-1].name >= name {
			return nil, fmt.Errorf("properties are not uniquely sorted at %q", name)
		}
		if kind == "b" && value != "true" && value != "false" {
			return nil, fmt.Errorf("invalid boolean property value %q", value)
		}
		if kind == "i" {
			if _, err := strconv.ParseInt(value, 10, 32); err != nil {
				return nil, fmt.Errorf("invalid int32 property value %q", value)
			}
		}
		properties = append(properties, defaultProperty{name: name, kind: kind, value: value})
	}
	return properties, nil
}

func goValue(property defaultProperty) string {
	switch property.kind {
	case "b":
		return property.value
	case "i":
		return "int32(" + property.value + ")"
	default:
		return fmt.Sprintf("%q", property.value)
	}
}
