package main

import (
	"fmt"
	"os"
	"strconv"
	"strings"
)

// occlusionRow is a state whose shape takes part in light occlusion with a
// face its occlusion shape only partly covers.
type occlusionRow struct {
	name, properties string
	faces            [6]string
}

// parseOcclusionRow parses an L row: the coverage of the six faces on the
// 16x16 pixel grid as four hex words each, or "-" for empty and full faces.
func parseOcclusionRow(fields []string) (occlusionRow, error) {
	row := occlusionRow{name: fields[1], properties: fields[2]}
	faces := strings.Split(fields[3], "/")
	if len(faces) != 6 {
		return row, fmt.Errorf("want 6 faces, got %d", len(faces))
	}
	for i, face := range faces {
		if face == "-" {
			continue
		}
		words := strings.Split(face, ",")
		if len(words) != 4 {
			return row, fmt.Errorf("face %d has %d words, want 4", i, len(words))
		}
		for _, word := range words {
			if _, err := strconv.ParseUint(word, 16, 64); err != nil {
				return row, err
			}
		}
		row.faces[i] = face
	}
	return row, nil
}

// writeOcclusion writes the partial occlusion faces of states as a table of
// distinct face bitmaps and the states that use them.
func writeOcclusion(path string, rows []occlusionRow) error {
	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by cmd/vanilla-solid-export from Java 26.3; DO NOT EDIT.")
	fmt.Fprint(&source, "// Coverage of partial BlockState.getFaceOcclusionShape faces on the 16x16 pixel grid.\n\npackage gamedata\n\n")
	bitmaps := map[string]int{}
	var order []string
	index := func(face string) int {
		if face == "" {
			return 0
		}
		if i, ok := bitmaps[face]; ok {
			return i
		}
		order = append(order, face)
		bitmaps[face] = len(order)
		return len(order)
	}
	var states strings.Builder
	for _, row := range rows {
		var faces [6]int
		for i, face := range row.faces {
			faces[i] = index(face)
		}
		fmt.Fprintf(&states, "\t{%q, %q, [6]uint16{%d, %d, %d, %d, %d, %d}},\n", row.name, row.properties, faces[0], faces[1], faces[2], faces[3], faces[4], faces[5])
	}
	fmt.Fprintln(&source, "var lightOcclusionBitmaps = [...][4]uint64{\n\t{},")
	for _, face := range order {
		fmt.Fprintf(&source, "\t{0x%s},\n", strings.ReplaceAll(face, ",", ", 0x"))
	}
	fmt.Fprintln(&source, "}\n\nvar lightOcclusionStates = [...]lightOcclusionState{")
	source.WriteString(states.String())
	fmt.Fprintln(&source, "}")
	return os.WriteFile(path, []byte(source.String()), 0o644)
}
