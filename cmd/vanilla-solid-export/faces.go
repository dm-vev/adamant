package main

import (
	"fmt"
	"go/format"
	"math"
	"os"
	"slices"
	"strconv"
	"strings"
)

type faceState struct {
	properties []defaultProperty
	mask       uint64
	rigid      uint8
	geometry   string
}

type faceProperty struct {
	name   string
	values []defaultProperty
}

type parsedGeometry struct {
	boundaries [6][][4]float64
	regions    [6][][4]float64
}

func generateFaces(path string, names []string, rows [][]faceState) error {
	var out strings.Builder
	fmt.Fprintln(&out, "// Code generated by cmd/vanilla-solid-export from Java 26.3; DO NOT EDIT.")
	fmt.Fprint(&out, "// EmptyBlockGetter models fresh generation: closed shulkers and no active moving-piston block entities; dynamic runtime shapes are not covered.\n\npackage gamedata\n\n")
	geometryIDs := make(map[string]int)
	var geometries []parsedGeometry
	for _, states := range rows {
		for _, state := range states {
			if _, exists := geometryIDs[state.geometry]; exists {
				continue
			}
			geometry, err := parseGeometry(state.geometry)
			if err != nil {
				return err
			}
			if len(geometries) > int(^uint16(0)) {
				return fmt.Errorf("collision geometry table exceeds uint16 index capacity")
			}
			geometryIDs[state.geometry] = len(geometries)
			geometries = append(geometries, geometry)
		}
	}
	fmt.Fprintln(&out, "var generationCollisionGeometries = [...]generationCollisionGeometry{")
	for _, geometry := range geometries {
		fmt.Fprint(&out, "\t{boundaries: [6][]generationCollisionRect{")
		writeRects(&out, geometry.boundaries)
		fmt.Fprint(&out, "}, regions: [6][]generationCollisionRect{")
		writeRects(&out, geometry.regions)
		fmt.Fprintln(&out, "}},")
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "\nvar generationFaceBlocks = [...]generationFaceBlock{")
	for i, states := range rows {
		properties, masks, rigid, shapeIDs, err := faceLayout(states, geometryIDs)
		if err != nil {
			return fmt.Errorf("%s: %w", names[i], err)
		}
		fmt.Fprintln(&out, "\t{")
		if len(properties) > 0 {
			fmt.Fprintln(&out, "\t\tproperties: []generationFaceProperty{")
			for _, property := range properties {
				fmt.Fprintf(&out, "\t\t\t{name:%q, values:[]any{", property.name)
				for _, value := range property.values {
					fmt.Fprintf(&out, "%s,", goValue(value))
				}
				fmt.Fprintln(&out, "}},")
			}
			fmt.Fprintln(&out, "\t\t},")
		}
		fmt.Fprint(&out, "\t\tmasks: []uint64{")
		for j, mask := range masks {
			if j%16 == 0 {
				fmt.Fprint(&out, "\n\t\t\t")
			}
			fmt.Fprintf(&out, "%d,", mask)
		}
		fmt.Fprint(&out, "\n\t\t},\n\t\trigid: []uint8{")
		for j, mask := range rigid {
			if j%24 == 0 {
				fmt.Fprint(&out, "\n\t\t\t")
			}
			fmt.Fprintf(&out, "%d,", mask)
		}
		fmt.Fprint(&out, "\n\t\t},\n\t\tgeometry: []uint16{")
		for j, id := range shapeIDs {
			if j%24 == 0 {
				fmt.Fprint(&out, "\n\t\t\t")
			}
			fmt.Fprintf(&out, "%d,", id)
		}
		fmt.Fprintln(&out, "\n\t\t},\n\t},")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0644)
}

func writeRects(out *strings.Builder, faces [6][][4]float64) {
	for _, face := range faces {
		fmt.Fprint(out, "{")
		for _, rect := range face {
			fmt.Fprintf(out, "{%s,%s,%s,%s},", strconv.FormatFloat(rect[0], 'g', -1, 64), strconv.FormatFloat(rect[1], 'g', -1, 64), strconv.FormatFloat(rect[2], 'g', -1, 64), strconv.FormatFloat(rect[3], 'g', -1, 64))
		}
		fmt.Fprint(out, "},")
	}
}

func parseGeometry(encoded string) (parsedGeometry, error) {
	var geometry parsedGeometry
	boundary, regions, ok := strings.Cut(encoded, "^")
	if !ok {
		return geometry, fmt.Errorf("collision geometry is missing face regions")
	}
	if strings.Contains(regions, "^") {
		return geometry, fmt.Errorf("collision geometry has multiple region separators")
	}
	if err := parseRectFaces(boundary, &geometry.boundaries); err != nil {
		return geometry, err
	}
	if err := parseRectFaces(regions, &geometry.regions); err != nil {
		return geometry, err
	}
	return geometry, nil
}

func parseRectFaces(encoded string, faces *[6][][4]float64) error {
	groups := strings.Split(encoded, "/")
	if len(groups) != 6 {
		return fmt.Errorf("collision geometry has %d faces, want 6", len(groups))
	}
	for face, encodedRects := range groups {
		if encodedRects == "" {
			continue
		}
		for _, encodedRect := range strings.Split(encodedRects, "|") {
			parts := strings.Split(encodedRect, ",")
			if len(parts) != 4 {
				return fmt.Errorf("invalid collision rectangle %q", encodedRect)
			}
			var rect [4]float64
			for i, part := range parts {
				value, err := strconv.ParseFloat(part, 64)
				if err != nil || math.IsNaN(value) || math.IsInf(value, 0) {
					return fmt.Errorf("invalid collision bound %q", part)
				}
				rect[i] = value
			}
			if rect[0] >= rect[2] || rect[1] >= rect[3] {
				return fmt.Errorf("empty collision rectangle %q", encodedRect)
			}
			faces[face] = append(faces[face], rect)
		}
	}
	return nil
}

func faceLayout(rows []faceState, geometryIDs map[string]int) ([]faceProperty, []uint64, []uint8, []int, error) {
	if len(rows) == 0 {
		return nil, nil, nil, nil, fmt.Errorf("missing generation faces")
	}
	schema := make([]faceProperty, len(rows[0].properties))
	for j, property := range rows[0].properties {
		schema[j].name = property.name
	}
	for _, row := range rows {
		if len(row.properties) != len(schema) {
			return nil, nil, nil, nil, fmt.Errorf("inconsistent property count")
		}
		for j, property := range row.properties {
			if property.name != schema[j].name {
				return nil, nil, nil, nil, fmt.Errorf("inconsistent property names")
			}
			if !slices.Contains(schema[j].values, property) {
				schema[j].values = append(schema[j].values, property)
			}
		}
	}
	total := 1
	for j := range schema {
		slices.SortFunc(schema[j].values, func(a, b defaultProperty) int { return strings.Compare(a.kind+":"+a.value, b.kind+":"+b.value) })
		total *= len(schema[j].values)
	}
	if total != len(rows) {
		return nil, nil, nil, nil, fmt.Errorf("incomplete state product: %d rows, want %d", len(rows), total)
	}
	masks, rigid, shapeIDs := make([]uint64, total), make([]uint8, total), make([]int, total)
	seen := make([]bool, total)
	for _, row := range rows {
		index := 0
		for j, property := range row.properties {
			index = index*len(schema[j].values) + slices.Index(schema[j].values, property)
		}
		if seen[index] {
			return nil, nil, nil, nil, fmt.Errorf("duplicate face state")
		}
		seen[index], masks[index], rigid[index], shapeIDs[index] = true, row.mask, row.rigid, geometryIDs[row.geometry]
	}
	// Drop state-property axes only when every generated value, including
	// rigid support and exact collision rectangles, is invariant on that axis.
	stride := 1
	for j := len(schema) - 1; j >= 0; j-- {
		radix := len(schema[j].values)
		matters := false
		for index := range masks {
			base := index - index/stride%radix*stride
			if masks[index] != masks[base] || rigid[index] != rigid[base] || shapeIDs[index] != shapeIDs[base] {
				matters = true
				break
			}
		}
		if matters {
			stride *= radix
			continue
		}
		reducedMasks := make([]uint64, 0, len(masks)/radix)
		reducedRigid := make([]uint8, 0, len(rigid)/radix)
		reducedShapes := make([]int, 0, len(shapeIDs)/radix)
		for index := range masks {
			if index/stride%radix == 0 {
				reducedMasks = append(reducedMasks, masks[index])
				reducedRigid = append(reducedRigid, rigid[index])
				reducedShapes = append(reducedShapes, shapeIDs[index])
			}
		}
		masks, rigid, shapeIDs = reducedMasks, reducedRigid, reducedShapes
		schema = slices.Delete(schema, j, j+1)
	}
	return schema, masks, rigid, shapeIDs, nil
}

func sameProperties(a, b []defaultProperty) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}
