package main

import (
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

type faceState struct {
	properties []defaultProperty
	mask       uint32
}

type faceProperty struct {
	name   string
	values []defaultProperty
}

func generateFaces(path string, names []string, rows [][]faceState) error {
	var out strings.Builder
	fmt.Fprintln(&out, "// Code generated by cmd/vanilla-solid-export from Java 26.3; DO NOT EDIT.")
	fmt.Fprint(&out, "// EmptyBlockGetter models fresh generation: no active moving pistons or open shulkers.\n\npackage javadata\n\n")
	fmt.Fprintln(&out, "var javaGenerationFaceBlocks = [...]generationFaceBlock{")
	for i, states := range rows {
		properties, masks, err := faceLayout(states)
		if err != nil {
			return fmt.Errorf("%s: %w", names[i], err)
		}
		fmt.Fprintln(&out, "\t{")
		if len(properties) > 0 {
			fmt.Fprintln(&out, "\t\tproperties: []generationFaceProperty{")
			for _, property := range properties {
				fmt.Fprintf(&out, "\t\t\t{name:%q, values:[]any{", property.name)
				for _, value := range property.values {
					fmt.Fprintf(&out, "%s,", goValue(value))
				}
				fmt.Fprintln(&out, "}},")
			}
			fmt.Fprintln(&out, "\t\t},")
		}
		fmt.Fprint(&out, "\t\tmasks: []uint32{")
		for j, mask := range masks {
			if j%16 == 0 {
				fmt.Fprint(&out, "\n\t\t\t")
			}
			fmt.Fprintf(&out, "%d,", mask)
		}
		fmt.Fprintln(&out, "\n\t\t},\n\t},")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0644)
}

func faceLayout(rows []faceState) ([]faceProperty, []uint32, error) {
	if len(rows) == 0 {
		return nil, nil, fmt.Errorf("missing generation faces")
	}
	schema := make([]faceProperty, len(rows[0].properties))
	for j, property := range rows[0].properties {
		schema[j].name = property.name
	}
	for _, row := range rows {
		if len(row.properties) != len(schema) {
			return nil, nil, fmt.Errorf("inconsistent property count")
		}
		for j, property := range row.properties {
			if property.name != schema[j].name {
				return nil, nil, fmt.Errorf("inconsistent property names")
			}
			if !slices.Contains(schema[j].values, property) {
				schema[j].values = append(schema[j].values, property)
			}
		}
	}
	total := 1
	for j := range schema {
		slices.SortFunc(schema[j].values, func(a, b defaultProperty) int { return strings.Compare(a.kind+":"+a.value, b.kind+":"+b.value) })
		total *= len(schema[j].values)
	}
	if total != len(rows) {
		return nil, nil, fmt.Errorf("incomplete state product: %d rows, want %d", len(rows), total)
	}
	masks := make([]uint32, total)
	for i := range masks {
		masks[i] = ^uint32(0)
	}
	for _, row := range rows {
		index := 0
		for j, property := range row.properties {
			index = index*len(schema[j].values) + slices.Index(schema[j].values, property)
		}
		if masks[index] != ^uint32(0) {
			return nil, nil, fmt.Errorf("duplicate face state")
		}
		masks[index] = row.mask
	}
	// Properties such as waterlogged often do not affect faces. Remove their
	// axes offline so generation performs only the comparisons that matter.
	stride := 1
	for j := len(schema) - 1; j >= 0; j-- {
		radix := len(schema[j].values)
		matters := false
		for index, mask := range masks {
			if mask != masks[index-(index/stride%radix)*stride] {
				matters = true
				break
			}
		}
		if matters {
			stride *= radix
			continue
		}
		reduced := make([]uint32, 0, len(masks)/radix)
		for index, mask := range masks {
			if index/stride%radix == 0 {
				reduced = append(reduced, mask)
			}
		}
		masks = reduced
		schema = slices.Delete(schema, j, j+1)
	}
	return schema, masks, nil
}
