// Command constimport writes the constants of gophertunnel's protocol and
// packet packages, protocol 2193, into the v2193 package of the net module
// with their values, so that the server names them without gophertunnel:
//
//	cd net/interop && go run ./cmd/constimport -o ../bedrock/proto/v2193/consts.go
//
// Constants v2193 already declares with the same value are left out; one
// with another value stops it. The abilities, bits in protocol and the
// indices of RequestAbility in packet, take the suffix Index for the
// latter.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/constant"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	protocolPath = "github.com/sandertv/gophertunnel/minecraft/protocol"
	packetPath   = "github.com/sandertv/gophertunnel/minecraft/protocol/packet"
	v2193Path    = "github.com/dm-vev/adamant/net/bedrock/proto/v2193"
)

type entry struct {
	name, typ, from string
	val             constant.Value
}

func main() {
	out := flag.String("o", "", "file to write")
	flag.Parse()
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName | packages.NeedSyntax | packages.NeedTypesInfo}, protocolPath, packetPath, v2193Path)
	if err != nil {
		log.Fatal(err)
	}
	var existing *types.Scope
	var declaredElsewhere func(obj types.Object) bool
	entries := map[string]entry{}
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			log.Fatalf("%s: %v", p.PkgPath, p.Errors)
		}
		if p.PkgPath == v2193Path {
			existing = p.Types.Scope()
			declaredElsewhere = handWritten(p)
		}
	}
	for _, p := range pkgs {
		if p.PkgPath == v2193Path {
			continue
		}
		scope := p.Types.Scope()
		for _, name := range scope.Names() {
			c, ok := scope.Lookup(name).(*types.Const)
			if !ok || !c.Exported() {
				continue
			}
			e := entry{name: name, typ: basicType(c.Type()), val: c.Val(), from: p.Name}
			if old, ok := entries[name]; ok && !constant.Compare(old.val, token.EQL, e.val) {
				// The abilities are bits in protocol and indices in packet,
				// the indices of RequestAbility.
				if !strings.HasPrefix(name, "Ability") {
					log.Fatalf("%s is %s in %s and %s in %s", name, old.val, old.from, e.val, e.from)
				}
				if e.from == "packet" {
					e.name = name + "Index"
				} else {
					old.name = name + "Index"
					entries[old.name] = old
				}
			} else if ok {
				continue
			}
			if obj := existing.Lookup(e.name); obj != nil && declaredElsewhere(obj) {
				if v, ok := obj.(*types.Const); ok && constant.Compare(v.Val(), token.EQL, e.val) {
					continue
				}
				log.Fatalf("v2193 already declares %s otherwise", e.name)
			}
			entries[e.name] = e
		}
	}
	names := make([]string, 0, len(entries))
	for n := range entries {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString(header + " from gophertunnel v1.62.0; DO NOT EDIT.\n\npackage v2193\n\n")
	b.WriteString("// Constants of protocol 2193: identifiers of packets, kinds of their\n// fields and values their fields take.\nconst (\n")
	for _, n := range names {
		e := entries[n]
		if e.typ == "" {
			fmt.Fprintf(&b, "\t%s = %s\n", e.name, literal(e.val))
		} else {
			fmt.Fprintf(&b, "\t%s %s = %s\n", e.name, e.typ, literal(e.val))
		}
	}
	b.WriteString(")\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d constants", len(names))
}

// header begins the files constimport writes.
const header = "// Code generated by constimport"

// handWritten returns whether an object of v2193 is declared in a file
// constimport did not write: the declarations of a file it wrote are the
// ones it writes anew, wherever it writes them.
func handWritten(p *packages.Package) func(obj types.Object) bool {
	generated := map[string]bool{}
	for _, f := range p.Syntax {
		if len(f.Comments) > 0 && strings.HasPrefix(f.Comments[0].List[0].Text, header) {
			generated[p.Fset.Position(f.Pos()).Filename] = true
		}
	}
	return func(obj types.Object) bool {
		return !generated[p.Fset.Position(obj.Pos()).Filename]
	}
}

// literal returns the value of a constant as Go source of its kind: a
// fraction such as 1/20, written as it is, would divide integers to 0, so
// a float is written as a float.
func literal(v constant.Value) string {
	if v.Kind() != constant.Float {
		return v.ExactString()
	}
	if f, exact := constant.Float64Val(v); exact {
		s := strconv.FormatFloat(f, 'g', -1, 64)
		if !strings.ContainsAny(s, ".e") {
			s += ".0"
		}
		return s
	}
	num, den, _ := strings.Cut(v.ExactString(), "/")
	return num + ".0 / " + den
}

// basicType returns the basic type a constant has, "" for an untyped one.
func basicType(t types.Type) string {
	b, ok := t.Underlying().(*types.Basic)
	if !ok || b.Info()&types.IsUntyped != 0 {
		return ""
	}
	return strings.TrimPrefix(b.String(), "untyped ")
}
