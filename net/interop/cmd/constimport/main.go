// Command constimport writes the constants of gophertunnel's protocol and
// packet packages, protocol 2193, into the v2193 package of the net module
// with their values, so that the server names them without gophertunnel:
//
//	cd net/interop && go run ./cmd/constimport -o ../bedrock/proto/v2193/consts.go
//
// Constants v2193 already declares with the same value are left out; one
// with another value stops it. The abilities, bits in protocol and the
// indices of RequestAbility in packet, take the suffix Index for the
// latter.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/constant"
	"go/format"
	"go/types"
	"log"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	protocolPath = "github.com/sandertv/gophertunnel/minecraft/protocol"
	packetPath   = "github.com/sandertv/gophertunnel/minecraft/protocol/packet"
	v2193Path    = "github.com/dm-vev/adamant/net/bedrock/proto/v2193"
)

type entry struct {
	name, typ, value, from string
}

func main() {
	out := flag.String("o", "", "file to write")
	flag.Parse()
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName | packages.NeedSyntax | packages.NeedTypesInfo}, protocolPath, packetPath, v2193Path)
	if err != nil {
		log.Fatal(err)
	}
	var existing *types.Scope
	entries := map[string]entry{}
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			log.Fatalf("%s: %v", p.PkgPath, p.Errors)
		}
		if p.PkgPath == v2193Path {
			existing = p.Types.Scope()
		}
	}
	for _, p := range pkgs {
		if p.PkgPath == v2193Path {
			continue
		}
		scope := p.Types.Scope()
		for _, name := range scope.Names() {
			c, ok := scope.Lookup(name).(*types.Const)
			if !ok || !c.Exported() {
				continue
			}
			e := entry{name: name, typ: basicType(c.Type()), value: c.Val().ExactString(), from: p.Name}
			if c.Val().Kind() == constant.String {
				e.value = c.Val().ExactString()
			}
			if old, ok := entries[name]; ok && old.value != e.value {
				// The abilities are bits in protocol and indices in packet,
				// the indices of RequestAbility.
				if !strings.HasPrefix(name, "Ability") {
					log.Fatalf("%s is %s in %s and %s in %s", name, old.value, old.from, e.value, e.from)
				}
				if e.from == "packet" {
					e.name = name + "Index"
				} else {
					old.name = name + "Index"
					entries[old.name] = old
				}
			} else if ok {
				continue
			}
			if obj := existing.Lookup(e.name); obj != nil {
				if v, ok := obj.(*types.Const); ok && v.Val().ExactString() == e.value {
					continue
				}
				log.Fatalf("v2193 already declares %s otherwise", e.name)
			}
			entries[e.name] = e
		}
	}
	names := make([]string, 0, len(entries))
	for n := range entries {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by constimport from gophertunnel v1.62.0; DO NOT EDIT.\n\npackage v2193\n\n")
	b.WriteString("// Constants of protocol 2193: identifiers of packets, kinds of their\n// fields and values their fields take.\nconst (\n")
	for _, n := range names {
		e := entries[n]
		if e.typ == "" {
			fmt.Fprintf(&b, "\t%s = %s\n", e.name, e.value)
		} else {
			fmt.Fprintf(&b, "\t%s %s = %s\n", e.name, e.typ, e.value)
		}
	}
	b.WriteString(")\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d constants", len(names))
}

// basicType returns the basic type a constant has, "" for an untyped one.
func basicType(t types.Type) string {
	b, ok := t.Underlying().(*types.Basic)
	if !ok || b.Info()&types.IsUntyped != 0 {
		return ""
	}
	return strings.TrimPrefix(b.String(), "untyped ")
}
