// bedrockSoundName returns the Bedrock sound for a sound name, and false if
// Bedrock has none.
func bedrockSoundName(name string) (string, bool) {
	if b, ok := bedrockSoundNames[name]; ok {
		return b, b != ""
	}
	return name, true
}
