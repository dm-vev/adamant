#!/usr/bin/env python3
"""Generate the pinned native default-state piston component classifications."""

import argparse
import hashlib
import json
from pathlib import Path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    raw = args.input.read_bytes()
    data = json.loads(raw)
    if not data["complete"] or len(data["blocks"]) != 1477 or data["binary_sha256"] != "76d547f82e02c18d0986c30b47132c9cc4171d0f2df1c00649e50ff35788b321":
        raise RuntimeError("not the complete pinned original-BDS movable-component export")
    names = [b["name"] for b in data["blocks"]]
    if len(set(names)) != len(names):
        raise RuntimeError("duplicate native block types")
    groups = {k: [] for k in ("PushPull", "Push", "Popped", "Immovable")}
    sticky = []
    changed = []
    for b in data["blocks"]:
        if "changed_to" in b:
            changed.append(b["name"])
            continue
        if b.get("movement") not in groups or b.get("sticky") not in ("None", "Same"):
            raise RuntimeError("unreadable or unexpected component data: " + b["name"])
        groups[b["movement"]].append(b["name"])
        if b["sticky"] == "Same":
            sticky.append(b["name"])
    if len(changed) != 5:
        raise RuntimeError("native immediate-placement changes differ")
    lines = ["// Code generated by scripts/redstone_generate_piston_movability.py; DO NOT EDIT.",
             "// Original BDS 1.26.51.1 default-state BlockMovableComponent data.",
             "// Fixture SHA-256: " + hashlib.sha256(raw).hexdigest(),
             "// Five immediate placement changes remain explicit in the fixture.",
             "// Runtime piston actors, attachment direction and support are handled separately.",
             "", "package block", "", "type pistonMovement uint8", "", "const (",
             "\tpistonPushPull pistonMovement = iota", "\tpistonPush", "\tpistonPopped", "\tpistonImmovable", ")", "",
             "func nativePistonMovement(name string) pistonMovement {", "\tswitch name {"]
    for kind, value in (("Push", "pistonPush"), ("Popped", "pistonPopped"), ("Immovable", "pistonImmovable")):
        lines.append("\tcase " + ",\n\t\t".join(json.dumps(n) for n in sorted(groups[kind])) + ":")
        lines.append("\t\treturn " + value)
    lines += ["\t}", "\treturn pistonPushPull", "}", "", "func nativePistonSticky(name string) bool {",
              "\tswitch name {", "\tcase " + ", ".join(json.dumps(n) for n in sorted(sticky)) + ":",
              "\t\treturn true", "\t}", "\treturn false", "}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps(dict(blocks=len(names), components=sum(map(len, groups.values())),
                         unread=changed, movement={k: len(v) for k, v in groups.items()}, sticky=sticky)))
