#!/usr/bin/env python3
"""Generate item-escape flags from the pinned original-BDS block type capture."""
import argparse
import hashlib
import json
from pathlib import Path

if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture",type=Path,required=True)
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args()
    raw=args.fixture.read_bytes()
    data=json.loads(raw)
    if not data["complete"] or len(data["block_types"])!=1477 or data["binary_sha256"]!="76d547f82e02c18d0986c30b47132c9cc4171d0f2df1c00649e50ff35788b321":
        raise RuntimeError("incomplete or different original-BDS block type fixture")
    lines=["// Code generated by scripts/redstone_generate_item_escape_flags.py; DO NOT EDIT.",
           "// Original BDS 1.26.51.1 BlockType flags, not inferred from collision shapes.",
           "// Fixture SHA-256: "+hashlib.sha256(raw).hexdigest(),"","package entity","",
           "func nativeItemEscapeFlags(name string) (pushesOutItems bool, properties uint64) {","\tswitch name {"]
    for stair in (True,False):
        names=sorted(name for name,flags in data["block_types"].items() if flags["pushes_out_items"] and bool(flags["properties"]&1)==stair)
        if not names:continue
        lines.append("\tcase "+",\n\t\t".join(json.dumps(name) for name in names)+":")
        lines.append("\t\treturn true, "+str(int(stair)))
    lines += ["\t}","\treturn false, 0","}",""]
    args.output.write_text("\n".join(lines),encoding="utf-8")
